let language = 'fr';
let applying = false;
let scheduled = false;

export function getLanguage() {
  return language;
}

export function t(value) {
  if (language === 'en') {
    const direct = english[value];
    if (direct) return direct;
    for (const [pattern, replacement] of dynamicRules.en) {
      const match = value.match(pattern);
      if (match) return replacement(match);
    }
    return value;
  }
  const direct = reverse[value];
  if (direct) return direct;
  for (const [pattern, replacement] of dynamicRules.fr) {
    const match = value.match(pattern);
    if (match) return replacement(match);
  }
  return value;
}

function translateAttributes() {
  const attributes = ['placeholder', 'title', 'aria-label'];
  for (const element of document.querySelectorAll('[placeholder], [title], [aria-label]')) {
    for (const attribute of attributes) {
      if (!element.hasAttribute(attribute)) continue;
      const value = element.getAttribute(attribute);
      const translated = t(value);
      if (translated !== value) element.setAttribute(attribute, translated);
    }
  }
}

export function applyLanguage(nextLanguage = language) {
  language = nextLanguage === 'en' ? 'en' : 'fr';
  applying = true;
  document.documentElement.lang = language;
  document.title = language === 'en' ? 'Loupe — Research aid for official reports' : 'Loupe — Aide à l’identification pour signalements';
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const node of nodes) {
    const parent = node.parentElement;
    if (!parent || ['SCRIPT', 'STYLE', 'CODE', 'PRE'].includes(parent.tagName)) continue;
    const raw = node.nodeValue;
    const trimmed = raw.trim();
    if (!trimmed) continue;
    const translated = t(trimmed);
    if (translated === trimmed) continue;
    const leading = raw.slice(0, raw.length - raw.trimStart().length);
    const trailing = raw.slice(raw.trimEnd().length);
    node.nodeValue = `${leading}${translated}${trailing}`;
  }
  translateAttributes();
  applying = false;
}

export function watchLanguageChanges() {
  const observer = new MutationObserver(() => {
    if (applying || scheduled) return;
    scheduled = true;
    queueMicrotask(() => {
      scheduled = false;
      applyLanguage(language);
    });
  });
  observer.observe(document.body, { childList: true, subtree: true, characterData: true });
}

export function confirmMessage(value) {
  return globalThis.confirm(t(value));
}
